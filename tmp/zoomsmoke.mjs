import { chromium } from 'playwright';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport:{width:1440,height:900} });
await context.addInitScript(() => { window.confirm = () => true; });
const page = await context.newPage();
page.on('pageerror', e => console.log('PAGEERR ' + String(e).slice(0,160)));
await page.goto('http://127.0.0.1:8766/', { waitUntil:'networkidle' });
console.log('after goto: active=' + await page.evaluate(() => { const b = document.querySelector('.mode-card.active'); return b ? b.dataset.mode : 'none'; }));
await page.click('.mode-card[data-mode="zoom"]');
console.log('after zoom click: active=' + await page.evaluate(() => { const b = document.querySelector('.mode-card.active'); return b ? b.dataset.mode : 'none'; }));
await page.selectOption('#landingStaff', 'Garry Lewis');
console.log('after staff: active=' + await page.evaluate(() => { const b = document.querySelector('.mode-card.active'); return b ? b.dataset.mode : 'none'; }));
await page.click('#landingContinue');
console.log('after continue: appClass=' + await page.evaluate(() => document.querySelector('.app').className) + ' active=' + await page.evaluate(() => { const b = document.querySelector('.mode-card.active'); return b ? b.dataset.mode : 'none'; }));
await page.waitForTimeout(300);
console.log('after wait: appClass=' + await page.evaluate(() => document.querySelector('.app').className));
const tz = await page.evaluate(() => { const el = document.getElementById('timelineZoom'); return el ? getComputedStyle(el).display : 'missing'; });
console.log('timelineZoom display=' + tz);
await browser.close();
